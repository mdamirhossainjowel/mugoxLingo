import { LOCALES, DEFAULT_LOCALE, localeMeta, type Locale } from "@/i18n/config";
import { BRAND, PRODUCTION_URL } from "@/lib/brand";

/**
 * Turns whatever is in NEXT_PUBLIC_SITE_URL into a clean origin such as "https://mymugox.com".
 * A missing protocol ("mymugox.com") gets https (http for localhost); trailing slashes and paths are dropped; garbage falls back.
 */
export function normalizeSiteUrl(raw: string | undefined, fallback: string): string {
  const t = (raw ?? "").trim();
  if (!t) return fallback;
  const local = /^(localhost|127\.0\.0\.1|192\.168\.|10\.)/i.test(t.replace(/^[a-z]+:\/\//i, ""));
  const withProtocol = /^[a-z][a-z0-9+.-]*:\/\//i.test(t) ? t : `${local ? "http" : "https"}://${t}`;
  try { const u = new URL(withProtocol); return u.protocol === "http:" || u.protocol === "https:" ? u.origin : fallback; } catch { return fallback; }
}
export const siteUrl = normalizeSiteUrl(process.env.NEXT_PUBLIC_SITE_URL, process.env.NODE_ENV === "production" ? PRODUCTION_URL : "http://localhost:3000");

/** hreflang map for a path like "" or "/privacy", including x-default. Relative URLs (metadataBase resolves them). */
export function languageAlternates(path = ""): Record<string, string> {
  const out: Record<string, string> = {};
  for (const l of LOCALES) out[l.hreflang] = `/${l.code}${path}`;
  out["x-default"] = `/${DEFAULT_LOCALE}${path}`;
  return out;
}
export const ogLocale = (locale: Locale) => localeMeta(locale).og;
export const ogAlternateLocales = (locale: Locale) => LOCALES.filter((l) => l.code !== locale).map((l) => l.og);

/** For private pages (lessons, account, sign-in): never indexed, and the base URL is still set so social-image links resolve. */
export const noIndex = { metadataBase: new URL(siteUrl), robots: { index: false, follow: true } } as const;

/** The social-sharing image for a language (generated by app/[locale]/opengraph-image.tsx). Pages that set their own openGraph must list it again. */
export const ogImage = (locale: string) => [{ url: `/${locale}/opengraph-image`, width: 1200, height: 630, alt: BRAND.name }];
